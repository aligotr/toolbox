//! Реестр модулей интерфейса.
//!
//! Ядро на Rust ничего не знает о том, как модуль выглядит и где он в меню.
//! Поэтому разделение такое:
//!
//! * **Rust** регистрирует обработчики сообщений (что модуль умеет);
//! * **Vue** регистрирует пункт меню и компонент (как модуль выглядит).
//!
//! Чтобы добавить подсистему, достаточно создать её компонент и добавить
//! одну запись в `src/modules/index.ts`.

import type { Component } from "vue";

/** Описание подсистемы на стороне интерфейса. */
export interface UiModule {
  /** Идентификатор, совпадает по смыслу с `Module::id` в Rust. */
  id: string;
  /** Название пункта меню. */
  title: string;
  /** Короткое пояснение в шапке модуля. */
  description?: string;
  /** Символ иконки; позже можно заменить на SVG или набор иконок. */
  icon?: string;
  /** Компонент, который отображается в рабочей области. */
  component: Component;
  /** Порядок в меню; меньше — выше. */
  order?: number;
}

/** Возвращает модули в порядке, заданном полем `order`. */
export function sortedModules(modules: UiModule[]): UiModule[] {
  return [...modules].sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
}
