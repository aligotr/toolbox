// Текст отказа для журнала и подписей.
//
// Отказ Tauri приходит строкой, отказ JavaScript — исключением. Один способ
// превращения в текст нужен и рабочему пространству, и профилям: иначе один
// экран показывал бы `Error: ...`, а другой — голую причину.

/** Текст ошибки: исключение отдаёт сообщение, строка остаётся собой. */
export function describeError(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}
