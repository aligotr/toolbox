// Контракт инструмента для оболочки.
//
// Оболочка не знает ни имён, ни внутренностей инструментов: она получает
// готовые дескрипторы из точки сборки и рисует по ним сайдбар и вкладки.
// Поэтому тип живёт в `contracts`: его используют и `workbench`, и `app`,
// и сами инструменты, но никто не зависит от чужой реализации.
//
// Тип компонента — параметр, а не импорт Vue: контракт остаётся словарём
// обмена. Точный тип знает тот, кто собирает реестр (`app`) или рисует
// сетку (`workbench`); инструменту достаточно `typeof` своего компонента.

/** Описание инструмента на стороне интерфейса. */
export interface ToolDescriptor<TComponent = unknown> {
  /** Идентификатор, совпадает по смыслу с `Module::id` в Rust. */
  id: string;
  /** Название в сайдбаре и в заголовке вкладки. */
  title: string;
  /** Короткое пояснение: что инструмент делает. */
  description?: string;
  /** Класс иконки PrimeIcons, например `pi pi-bolt`. */
  icon: string;
  /** Порядок в сайдбаре; меньше — выше. */
  order?: number;
  /** Компонент, который отображается в ячейке вкладки. */
  component: TComponent;
}

/**
 * Проп, который оболочка передаёт инструменту в ячейке.
 *
 * Ключ уникален для места в сетке и переживает переключение вкладок:
 * `<tabId>:<columnIndex>:<toolIndex>` (ADR 0017). Инструменты без состояния
 * проп не объявляют и просто игнорируют его.
 */
export interface ToolCellProps {
  cellKey?: string;
}
