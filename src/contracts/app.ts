// Контракт сведений о программе: версия, режим сборки и папки.
//
// Одна структура на два раздела настроек: «Журнал» показывает файл лога,
// «Программа» — версию и папку. Пути выбирает ядро, интерфейс их только
// показывает: рабочая папка может быть сетевой, и собирать её из частей
// в UI значило бы повторить правила раскладки (ADR 0010).

/** Сведения о программе. */
export interface AppInfo {
  version: string;
  /** `true` — отладочная сборка (`cargo run`, `tauri dev`). */
  debug: boolean;
  /** Папка программы: рядом с ней лежат `local/` и `profiles/`. */
  root: string;
  /** Идентификатор активного профиля. */
  profile: string;
  /** Название активного профиля; без `profile.json` совпадает с id. */
  profile_title: string;
  /** Файл лога текущих суток; пусто, если лог не запущен. */
  log_path: string;
  /** Папка логов. */
  log_dir: string;
  /** Сколько дней ядро хранит логи. */
  log_keep_days: number;
}
