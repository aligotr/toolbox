// Контракт профилей: папка `profiles/<id>/` и название из `profile.json`.
//
// Идентификатор — имя папки, поэтому он стабилен: переименование меняет
// только название внутри файла. Интерфейсу нужны оба поля: по `id`
// переключаются, `title` показывают пользователю (ADR 0010).

/** Профиль для интерфейса. */
export interface Profile {
  /** Идентификатор: имя папки, только латиница, цифры, `-` и `_`. */
  id: string;
  /** Название для интерфейса. */
  title: string;
  /** Сколько шаблонов лежит в профиле. */
  templates: number;
  /** Сколько пресетов настроек лежит в профиле. */
  presets: number;
  /** Сколько файлов данных инструментов лежит в профиле. */
  data_files: number;
}

/** Список профилей вместе с активным. */
export interface ProfileList {
  /** Идентификатор активного профиля. */
  active: string;
  /** Профили в порядке названий. */
  items: Profile[];
}
