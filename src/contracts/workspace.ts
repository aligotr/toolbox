// Контракт рабочего пространства: вкладки и их колонки.
//
// Формат общий для памяти, файла `local/workspace.json` и шаблонов вкладок.
// Поэтому он описан отдельно от оболочки: оболочка показывает, core читает
// и пишет, шаблоны хранят ту же геометрию (ADR 0011).

/** Колонка вкладки: инструменты сверху вниз. */
export interface TabColumn {
  /** Ширина колонки в условных единицах; доли считаются от суммы по вкладке. */
  width: number;
  /** Идентификаторы инструментов в порядке сверху вниз. */
  tools: string[];
}

/** Чем занята вкладка. */
export type TabKind = "workspace" | "journal" | "settings";

/** Одиночная вкладка: существует в одном экземпляре. */
export type SingletonKind = "journal" | "settings";

/** Вкладка рабочего пространства. */
export interface WorkspaceTab {
  /** Идентификатор вкладки; уникален в пределах рабочего пространства. */
  id: string;
  kind: TabKind;
  /** Заголовок в полосе вкладок. */
  title: string;
  /** Класс иконки PrimeIcons. */
  icon: string;
  /** Колонки с инструментами; у журнала и настроек пусто. */
  columns: TabColumn[];
}

/**
 * Связка вкладки с шаблоном.
 *
 * Обе ревизии — отпечатки геометрии на момент сверки: `templateRev` у шаблона,
 * `layoutRev` у вкладки. По их расхождению видно, что изменилось, без хранения
 * второй копии раскладки. Ключ связки — идентификатор вкладки.
 */
export interface Binding {
  /** Шаблон, из которого пришла вкладка. */
  templateId: string;
  /** Отпечаток геометрии шаблона на момент сверки. */
  templateRev: string;
  /** Отпечаток геометрии вкладки на момент сверки. */
  layoutRev: string;
}

/** Содержимое файла `local/workspace.json`. */
export interface WorkspaceFile {
  /** Версия формата. Читается только совпадающая: чужая форма не угадывается. */
  version: number;
  /** Открытые вкладки в порядке полосы. */
  tabs: WorkspaceTab[];
  /** Активная вкладка; если её нет среди `tabs`, выбирается первая. */
  activeId: string;
  /** Связки вкладок с шаблонами; у вкладки без связки записи нет. */
  bindings: Record<string, Binding>;
}
