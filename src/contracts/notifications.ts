// Контракт уведомлений поверх экрана (ADR 0058).
//
// Ядро шлёт код словаря и параметры, а не готовый текст: язык интерфейса
// ему неизвестен. Форма живёт в контрактах, чтобы событие шины и приёмник
// говорили об одном и том же.

/** Вид уведомления: он же `severity` PrimeVue. */
export type NoticeKind = "info" | "success" | "warn" | "error";

/** Уведомление из шины: код словаря, подстановки и ключ замены. */
export interface NoticePayload {
  kind: NoticeKind;
  /** Ключ словаря: текст переводится при показе. */
  code: string;
  /** Подстановки сообщения. */
  params?: Record<string, string | number>;
  /** Русский текст, если ключа нет в словаре. */
  fallback?: string;
  /** Ключ замены: новое уведомление вытесняет предыдущее с той же группой. */
  group?: string;
}
