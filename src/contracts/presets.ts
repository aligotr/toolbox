// Контракт пресетов настроек.
//
// Пресет — файл `profiles/<id>/presets/<tool>/<presetId>.json` (ADR 0028):
// идентификатор в имени файла, название и настройки внутри документа.
// `payload` приходит как JSON без проверки: формат настроек принадлежит
// инструменту, и Rust его не разбирает. Поэтому тип честно говорит
// `unknown`, а разбор делает модуль инструмента.

import type { AppError } from "./errors";

/** Пресет, как его отдаёт ядро: настройки ещё не проверены. */
export interface StoredPreset {
  /** Идентификатор: имя файла без расширения. */
  id: string;
  /** Название для интерфейса. */
  title: string;
  /** Время сохранения в ISO-8601 UTC. */
  saved_at: string;
  /** Настройки инструмента: формат принадлежит инструменту. */
  payload: unknown;
}

/** Список пресетов вместе с замечаниями о непрочитанных файлах. */
export interface StoredPresetList {
  items: StoredPreset[];
  /** Причины, по которым часть файлов пропущена. */
  warnings: AppError[];
}

/** Указатель на пресет по умолчанию и замечание о файле профиля. */
export interface StoredPresetDefault {
  /** Идентификатор пресета; `null` — умолчание не задано. */
  id: string | null;
  /** Причина, по которой файл профиля не разобран; `null` — всё в порядке. */
  warning: AppError | null;
}
