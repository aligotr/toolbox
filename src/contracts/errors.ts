// Контракт отказа ядра (ADR 0039).
//
// Ядро присылает не готовую фразу, а смысл: код, данные подстановок и русский
// запасной текст. Код переводит словарь интерфейса, `params` остаются данными,
// а `fallback` показывает причину, когда перевода кода ещё нет.

/** Структурный отказ ядра: код, подстановки и русский запасной текст. */
export interface AppError {
  /** Код вида `errors.<область>.<случай>`: контракт с ядром. */
  code: string;
  /** Значения подстановок сообщения. */
  params: Record<string, string>;
  /** Русский текст на случай, если код ещё не переведён. */
  fallback: string;
}
