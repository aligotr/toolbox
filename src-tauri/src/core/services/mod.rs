//! Сервисы ядра: по одному домену на файл (ADR 0035).
//!
//! Домен владеет и правилами, и своим форматом: профиль — папкой
//! `profiles/<id>/`, настройки — `local/settings.json`, пресеты — файлами
//! пресетов и указателем по умолчанию, вкладки — `local/workspace.json`.
//!
//! Сервисы не имеют пункта в меню и не удаляются: без них приложение
//! не работает (ADR 0005). Подсистемы (`modules`) зовут их только через
//! шину, а не прямыми вызовами.
//!
//! Зависимости сервиса — [`crate::core::store`] и [`crate::core::infra`].
//! Связи между сервисами редки и видны по импортам: настройки читают
//! профили, окно читает настройки.

pub mod data;
pub mod languages;
pub mod logging;
pub mod presets;
pub mod profiles;
pub mod settings;
pub mod window;
pub mod workspace;
