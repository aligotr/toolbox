//! Базовые типы сообщений шины.
//!
//! В образце разделение такое:
//! - **Command** — изменяет состояние; на одну команду ровно один обработчик;
//! - **Event** — уведомляет о факте; на одно событие сколько угодно обработчиков.
//!
//! Отличие от Python-образца: там сообщения — обычные классы, а тип определялся
//! через `isinstance`. В Rust типы известны на этапе компиляции, поэтому каждое
//! сообщение обязано объявить свой **топик** (строковый идентификатор).
//! Топик нужен на границе с UI: фронтенд шлёт команду по имени топика и
//! подписывается на события по имени топика.

use std::any::Any;

/// Общий предок всех сообщений шины.
///
/// Требования `Send + Sync + 'static` нужны, чтобы сообщения можно было
/// передавать между потоками (события обрабатываются в фоновом потоке)
/// и хранить в очереди.
pub trait Message: Any + Send + Sync + 'static {
    /// Строковый идентификатор сообщения, например `"dns.lookup"`.
    /// Используется как имя при обмене между Rust и интерфейсом.
    const TOPIC: &'static str;
}

/// Команда — запрос на изменение состояния.
/// Контракт образца: у команды может быть **только один** обработчик.
pub trait Command: Message {}

/// Событие — уведомление о том, что уже произошло.
/// Контракт образца: у события может быть **много** обработчиков.
pub trait Event: Message {}
