//! Контейнер зависимостей (аналог инъекции зависимостей из образца).
//!
//! В Python-образце зависимости внедрялись **по имени** параметра обработчика:
//! шина смотрела на сигнатуру функции и подставляла значения из своего словаря.
//! В Rust рефлексии нет — сигнатуру функции во время выполнения прочитать нельзя.
//!
//! Поэтому здесь инъекция выполняется **по типу**: обработчик получает `&Deps`
//! и сам достаёт нужную зависимость методом [`Deps::get`]. Это тот же принцип
//! (обработчик не создаёт зависимости сам, а получает их извне), но выраженный
//! средствами типов Rust.

use std::any::{Any, TypeId};
use std::collections::HashMap;
use std::sync::{Arc, RwLock};

/// Хранилище зависимостей, доступное обработчикам шины.
///
/// Внутри — `Arc<RwLock<...>>`, поэтому `Deps` дёшево клонируется:
/// все клоны смотрят на одно и то же хранилище.
#[derive(Default, Clone)]
pub struct Deps {
    /// Ключ — тип зависимости, значение — сама зависимость,
    /// стёртая до `dyn Any`. Обёртка `Arc` позволяет отдавать её
    /// нескольким обработчикам одновременно.
    inner: Arc<RwLock<HashMap<TypeId, Arc<dyn Any + Send + Sync>>>>,
}

impl Deps {
    /// Создаёт пустой контейнер.
    pub fn new() -> Self {
        Self::default()
    }

    /// Регистрирует зависимость по её типу.
    ///
    /// Возвращает `&Self`, чтобы вызовы можно было выстраивать цепочкой:
    /// `Deps::new().add(logger).add(config)`.
    pub fn add<T: Send + Sync + 'static>(&self, value: T) -> &Self {
        self.inner
            .write()
            .expect("блокировка контейнера зависимостей отравлена")
            .insert(TypeId::of::<T>(), Arc::new(value));
        self
    }

    /// Возвращает зависимость по типу, если она зарегистрирована.
    pub fn get<T: Send + Sync + 'static>(&self) -> Option<Arc<T>> {
        self.inner
            .read()
            .expect("блокировка контейнера зависимостей отравлена")
            .get(&TypeId::of::<T>())
            .cloned()
            // downcast не может упасть: ключом служит TypeId того же типа.
            .and_then(|any| any.downcast::<T>().ok())
    }
}
