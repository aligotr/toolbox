//! Абстракция подсистемы (модуля).
//!
//! Модуль — самодостаточная единица платформы. Он знает свои топики и умеет
//! зарегистрировать свои обработчики в шине. Ядро при этом не знает ничего
//! о внутреннем устройстве модуля — только о его идентификаторе и факте
//! регистрации. Это и есть тот самый принцип слабой связанности.

use crate::core::infra::bus::MessageBus;

/// Подсистема платформы.
///
/// Реализация регистрирует свои события/команды в [`MessageBus`]. Никаких
/// прямых вызовов между модулями быть не должно — только сообщения.
pub trait Module: Send + Sync + 'static {
    /// Короткий идентификатор модуля, например `"dns"` или `"app"`.
    fn id(&self) -> &'static str;

    /// Регистрация обработчиков и маршрутов в шине.
    fn register(&self, bus: &MessageBus);
}
