//! Прямые команды жизненного цикла (ADR 0049).
//!
//! `exit_app`, `log_frontend` и `app_restart` идут мимо шины осознанно:
//! это не домен, а управление процессом. Шина при выходе может быть уже
//! не нужна или ещё не запущена, а отчёт об ошибке JS обязан дойти даже
//! при заблокированном запуске (ADR 0004).

use tauri::AppHandle;

/// Запись в лог из интерфейса. Нужна для ошибок JS и необработанных отказов:
/// иначе они не оставляют следа вообще.
///
/// Уровень не принимается параметром: перечень того, что пишет интерфейс,
/// закрыт и состоит только из ошибок. Лишний параметр рано или поздно
/// превратился бы в информационные сообщения из UI.
#[tauri::command]
pub(crate) fn log_frontend(message: String) -> Result<(), String> {
    log::error!("интерфейс: {message}");
    Ok(())
}

/// Выход без шины: нужен блокирующему экрану, когда модули не запущены.
#[tauri::command]
pub(crate) fn exit_app(app: AppHandle) {
    app.exit(0);
}

/// Перезапускает приложение.
///
/// `request_restart`, а не `restart`: выход обязан пройти общий путь
/// `RunEvent::Exit`, где дописываются геометрия окна и файл лога.
#[tauri::command]
pub(crate) fn app_restart(app: AppHandle) {
    log::info!("Перезапуск по запросу интерфейса");
    app.request_restart();
}
