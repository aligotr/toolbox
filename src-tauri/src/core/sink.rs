//! Приёмник событий — «выход» шины во внешний мир.
//!
//! Ядро не должно знать про Tauri: иначе его нельзя будет протестировать
//! без запуска приложения. Поэтому шина отдаёт события абстрактному
//! [`EventSink`], а конкретную реализацию (отправка в интерфейс через Tauri)
//! подставляет приложение при старте.

use serde_json::Value;

/// Получатель событий шины.
///
/// Реализация обязана быть потокобезопасной: события обрабатываются
/// в фоновом потоке-диспетчере.
pub trait EventSink: Send + Sync + 'static {
    /// Доставляет событие наружу: `topic` — имя события,
    /// `payload` — сериализованные данные.
    fn emit(&self, topic: &'static str, payload: Value);
}
